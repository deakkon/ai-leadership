KEYWORD_SEPARATOR = ","


def generate_content(
    conn: sqlite3.Connection, *, icp: str | None = None, use_llm: bool = False
) -> int:
    """Insert content ideas from the matrix (optionally one ICP). Returns count."""
    created = 0
    for row in CONTENT_MATRIX:
        item_icp, trigger, content_type, title, keywords = row
        if icp and item_icp != icp:
            continue
        if use_llm:
            result = llm.generate_text(
                f"Suggest an SEO/GEO-optimized {content_type} title and 5 keywords for the "
                f"buyer problem: {trigger} (ICP {item_icp}). "
                f"Format: title on first line, keywords comma-separated on second.",
                fallback_text=f"{title}\n{keywords}",
            )
            lines = result.text.splitlines()
            if len(lines) >= 2 and lines[0].strip():
                title = lines[0].strip()
                keywords = lines[1].strip()
        db.execute(
            conn,
            "INSERT INTO content_items (title, content_type, icp, trigger, keywords, status) "
            "VALUES (?, ?, ?, ?, ?, 'draft')",
            (title, content_type, item_icp, trigger, keywords),
        )
        created += 1
    conn.commit()
    return created


def list_content(conn: sqlite3.Connection, icp: str | None = None) -> list[sqlite3.Row]:
    sql = "SELECT * FROM content_items"
    params: tuple[object, ...] = ()
    if icp:
        sql += " WHERE icp = ?"
        params = (icp,)
    return db.rows(conn, sql + " ORDER BY id", params)
